def cmd_init(args):
    work = Work(args.workdir)
    if osp.exists(work.config_path) and not args.force:
        sys.exit(f"{work.root} is already initialised (use --force to re-initialise).")
    require(args.materials, "Give the folder with your idea and experimental log.")
    require(osp.join(args.template, "template.tex"), "Template folder needs template.tex")
    require(osp.join(args.template, "guidelines.md"), "Template folder needs guidelines.md")

    cfg = dict(DEFAULT_CONFIG)
    cfg["idea_filename"] = args.idea_filename
    cfg["experimental_log_filename"] = args.log_filename
    cfg["research_cutoff"] = args.cutoff or datetime.datetime.now().strftime("%Y-%m")
    for key in ("writer_model", "reflection_model", "plotting_model", "image_model"):
        if getattr(args, key):
            cfg[key] = getattr(args, key)

    for fname in (cfg["idea_filename"], cfg["experimental_log_filename"]):
        require(osp.join(args.materials, fname), f"Raw materials must contain {fname}")

    os.makedirs(work.root, exist_ok=True)
    if osp.abspath(args.materials) != work.materials:
        shutil.copytree(args.materials, work.materials, dirs_exist_ok=True)
    shutil.copytree(args.template, work.latex, dirs_exist_ok=True)
    shutil.copy(work.template, work.template_skeleton)
    os.makedirs(work.figures, exist_ok=True)
    if not osp.exists(work.figures_info):
        save_figures_info(work, [])
    with open(work.config_path, "w") as f:
        json.dump(cfg, f, indent=2)
    work.mark("init", materials=osp.abspath(args.materials), template=osp.abspath(args.template))

    print(f"Initialised {work.root}")
    print(json.dumps(cfg, indent=2))
    print(
        "\nBefore `outline`, review/edit:\n"
        f"   {work.idea}\n   {work.log}\n"
        f"   {work.template}   (title, authors, keywords, acknowledgments)\n"
        f"   {work.guidelines}"
    )


def cmd_outline(args):
    from google.genai import types  # noqa: F401  (ensures dependency is importable)
    from methods.agents.outline_agent import OutlineAgent

    work = Work(args.workdir)
    cfg = work.load_config()
    model = args.model or cfg["writer_model"]
    backup(work, "outline", [work.outline])

    t0 = time.time()
    OutlineAgent(model_name=model, cutoff_date=cfg["research_cutoff"]).run(
        idea_file=work.idea,
        experimental_log_file=work.log,
        latex_template_file=work.template_skeleton,
        conference_guidelines_file=work.guidelines,
        output_filepath=work.outline,
    )
    work.mark("outline", model=model)
    report(t0, [work.outline])
    print(
        "\nIn outline.json check: plotting_plan (figures to generate), "
        "intro_related_work_plan (search queries), section_plan (structure, citation_hints)."
    )


def cmd_literature(args):
    from methods.agents.literature_review_agent import HybridLiteratureAgent

    work = Work(args.workdir)
    cfg = work.load_config()
    require(work.outline, "Run `outline` first.")
    model = args.model or cfg["writer_model"]
    backup(work, "literature", [work.lit_dir, work.template])

    t0 = time.time()
    agent = HybridLiteratureAgent(
        idea_path=work.idea,
        experimental_log_path=work.log,
        latex_template_path=work.template_skeleton,
        conference_guidelines_path=work.guidelines,
        output_dir=work.lit_dir,
        model_name=model,
        max_workers=cfg["literature_max_workers"],
        must_cite_path=osp.join(work.materials, "must_cite.txt"),
        must_cite_bib_path=osp.join(work.materials, "must_cite.bib"),
    )
    agent.run(outline_path=work.outline, cutoff_date=cfg["research_cutoff"])

    # Same hand-off as the original pipeline: the filled-in template and the
    # bibliography become the writer's starting point.
    shutil.copy(osp.join(work.lit_dir, "updated_template.tex"), work.template)
    shutil.copy(osp.join(work.lit_dir, "references.bib"), osp.join(work.latex, "references.bib"))
    work.mark("literature", model=model)

    pdf = compile_tex(work.template)
    report(
        t0,
        [
            osp.join(work.lit_dir, "references.bib"),
            work.citation_map,
            work.template,
            pdf or osp.join(work.latex, "template.pdf"),
        ],
    )
    print(
        "\nReview the cited papers (citation_map.json) and the Introduction/Related Work in "
        "latex_writeup/template.tex. Edits to template.tex are kept by `write`."
    )


def cmd_plotting(args):
    from methods.agents.plotting_agent import PlottingAgent

    work = Work(args.workdir)
    cfg = work.load_config()
    require(work.outline, "Run `outline` first.")
    model = args.model or cfg["plotting_model"]
    backup(work, "plotting", [work.plot_dir])

    t0 = time.time()
    results = PlottingAgent(
        model_name=model,
        image_model_name=args.image_model or cfg["image_model"],
        max_critic_rounds=cfg["plotting_max_critic_rounds"],
    ).run(
        outline_json_path=work.outline,
        raw_materials_dir=work.materials,
        output_filepath=work.plot_results,
    )

    # Register generated figures (replacing earlier generated ones, keeping user figures).
    info = [f for f in load_figures_info(work) if f.get("source") != "plotting_agent"]
    new_files = []
    for res in results or []:
        if "image_path" not in res:
            continue
        src = osp.join(work.plot_dir, res["image_path"])
        if not osp.exists(src):
            continue
        name = osp.basename(src)
        shutil.copy(src, osp.join(work.figures, name))
        info.append({"name": name, "caption": res.get("caption", ""), "source": "plotting_agent"})
        new_files.append(osp.join(work.figures, name))
    save_figures_info(work, info)
    work.mark("plotting", model=model, n_figures=len(new_files))
    report(t0, [work.plot_results, work.figures_info] + new_files)


def cmd_add_figure(args):
    work = Work(args.workdir)
    work.load_config()
    require(args.file, "Figure file not found.")
    ext = osp.splitext(args.file)[1].lower()
    if ext not in FIGURE_EXTS:
        sys.exit(f"Unsupported figure type {ext}; use one of {FIGURE_EXTS}")
    name = args.name or osp.basename(args.file)
    shutil.copy(args.file, osp.join(work.figures, name))
    info = [f for f in load_figures_info(work) if f["name"] != name]
    info.append({"name": name, "caption": args.caption, "source": "user"})
    save_figures_info(work, info)
    print(f"Added figures/{name}. Registered figures:")
    for f in info:
        print(f"   [{f.get('source', '?')}] {f['name']}: {f['caption'][:80]}")


def cmd_remove_figure(args):
    work = Work(args.workdir)
    info = load_figures_info(work)
    kept = [f for f in info if f["name"] != args.name]
    if len(kept) == len(info):
        sys.exit(f"No registered figure named {args.name}")
    save_figures_info(work, kept)
    print(f"Unregistered {args.name} (file left in figures/).")


def cmd_write(args):
    from methods.agents.section_writing_agent import SectionWritingAgent

    work = Work(args.workdir)
    cfg = work.load_config()
    require(work.citation_map, "Run `literature` first.")
    model = args.model or cfg["writer_model"]
