"""Run the PaperOrchestra pipeline one step at a time, for human review in between.

The pipeline in `methods/paper_writer_with_plotting.py` runs all agents in one go and
wipes its output folder on every run. This runner calls the same agents, but each step
reads the (possibly hand-edited) output files of the previous step from a work
directory, and a rerun first backs up the files it is about to overwrite to
`<workdir>/history/`.

Steps (run in this order; `plotting` and `add-figure` are optional):

    init        create the work directory from raw materials and a LaTeX template
    outline     -> outline.json                          (edit before `literature`)
    literature  -> literature_agent_output/{references.bib, citation_map.json,
                   updated_template.tex, outline_v1.json}; Introduction + Related
                   Work are written into latex_writeup/template.tex
    plotting    -> figures generated by the plotting agent (LLM-written matplotlib
                   code is executed locally; diagrams use the image model)
    add-figure  register your own figure file + caption for the writer to use
    write       -> latex_writeup/raw_draft_paper.tex (+ compiled raw_draft_paper.pdf)
    refine      -> refine/round_N/ (reviewer feedback, revised .tex and .pdf)
    status      show what has been done and where the files are

Examples:

    python run_steps.py init --workdir work/paper1 --materials my_materials \
        --template templates/aastex7 --cutoff 2026-11
    python run_steps.py outline --workdir work/paper1
    python run_steps.py literature --workdir work/paper1
    python run_steps.py add-figure --workdir work/paper1 --file fig1.pdf \
        --caption "Telluric transmission in the H band ..."
    python run_steps.py write --workdir work/paper1
    python run_steps.py refine --workdir work/paper1 --rounds 1
    python run_steps.py status --workdir work/paper1

Models are stored in <workdir>/config.json (set them at `init`, edit the file, or pass
--model to a step to override it for that run).
"""

import argparse
import datetime
import json
import os
import os.path as osp
import shutil
import sys
import time

REPO_DIR = osp.dirname(osp.abspath(__file__))
sys.path.insert(0, REPO_DIR)

DEFAULT_CONFIG = {
    "idea_filename": "idea.md",
    "experimental_log_filename": "experimental_log.md",
    "research_cutoff": None,  # YYYY-MM; set at init
    "writer_model": "google/gemini-3.1-pro-preview",
    "reflection_model": "google/gemini-3.1-pro-preview",
    "plotting_model": "google/gemini-3.1-pro-preview",
    "image_model": "google/gemini-3-pro-image",
    "plotting_max_critic_rounds": 3,
    "literature_max_workers": 3,
}

FIGURE_EXTS = (".pdf", ".png", ".jpg")  # what the section writer understands


# --------------------------------------------------------------------------- helpers


class Work:
    """Paths inside a work directory (same layout as the original pipeline)."""

    def __init__(self, workdir: str):
        self.root = osp.abspath(workdir)
        self.config_path = osp.join(self.root, "config.json")
        self.state_path = osp.join(self.root, "state.json")
        self.materials = osp.join(self.root, "raw_materials")
        self.latex = osp.join(self.root, "latex_writeup")
        self.figures = osp.join(self.latex, "figures")
        self.figures_info = osp.join(self.figures, "info.json")
        self.template = osp.join(self.latex, "template.tex")
        self.template_skeleton = osp.join(self.latex, "template_skeleton.tex")
        self.guidelines = osp.join(self.latex, "guidelines.md")
        self.outline = osp.join(self.root, "outline.json")
        self.lit_dir = osp.join(self.root, "literature_agent_output")
        self.lit_outline = osp.join(self.lit_dir, "outline_v1.json")
        self.citation_map = osp.join(self.lit_dir, "citation_map.json")
        self.plot_dir = osp.join(self.root, "plotting_output")
        self.plot_results = osp.join(self.plot_dir, "plotting_results.json")
        self.draft = osp.join(self.latex, "raw_draft_paper.tex")
        self.refine_dir = osp.join(self.root, "refine")
        self.history = osp.join(self.root, "history")

    # config / state -------------------------------------------------------
    def load_config(self) -> dict:
        if not osp.exists(self.config_path):
            sys.exit(f"No config at {self.config_path}. Run `init` first.")
        with open(self.config_path) as f:
            cfg = dict(DEFAULT_CONFIG)
            cfg.update(json.load(f))
        return cfg

    def load_state(self) -> dict:
        if osp.exists(self.state_path):
            with open(self.state_path) as f:
                return json.load(f)
        return {}

    def mark(self, step: str, **info):
        state = self.load_state()
        state[step] = {"finished": datetime.datetime.now().isoformat(timespec="seconds"), **info}
        with open(self.state_path, "w") as f:
            json.dump(state, f, indent=2)

    @property
    def idea(self):
        return osp.join(self.materials, self.load_config()["idea_filename"])

    @property
    def log(self):
        return osp.join(self.materials, self.load_config()["experimental_log_filename"])

    def refine_rounds(self):
        if not osp.isdir(self.refine_dir):
            return []
        rounds = [d for d in os.listdir(self.refine_dir) if d.startswith("round_")]
        return sorted(rounds, key=lambda d: int(d.split("_")[1]))


def backup(work: Work, step: str, paths):
    """Copy existing outputs of a step to history/<step>_<timestamp>/ before overwriting."""
    existing = [p for p in paths if osp.exists(p)]
    if not existing:
        return
    stamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    dest = osp.join(work.history, f"{step}_{stamp}")
    os.makedirs(dest, exist_ok=True)
    for p in existing:
        target = osp.join(dest, osp.relpath(p, work.root))
        os.makedirs(osp.dirname(target), exist_ok=True)
        if osp.isdir(p):
            shutil.copytree(p, target)
        else:
            shutil.copy2(p, target)
    print(f" >> Previous outputs backed up to {dest}")


def require(path: str, hint: str):
    if not osp.exists(path):
        sys.exit(f"Missing {path}\n   -> {hint}")


def load_figures_info(work: Work) -> list:
    if osp.exists(work.figures_info):
        with open(work.figures_info) as f:
            return json.load(f)
    return []


def save_figures_info(work: Work, info: list):
    os.makedirs(work.figures, exist_ok=True)
    with open(work.figures_info, "w") as f:
        json.dump(info, f, indent=4)


def compile_tex(tex_path: str) -> str:
    from utils.pdf_utils import compile_latex

    d, name = osp.split(tex_path)
    stem = osp.splitext(name)[0]
    pdf = osp.join(d, f"{stem}.pdf")
    compile_latex(d, pdf, stem, timeout=60)
    return pdf if osp.exists(pdf) else None


def report(t0: float, outputs):
    print(f"\n>> Done in {time.time() - t0:.0f}s. Review these files:")
    for p in outputs:
        flag = "" if osp.exists(p) else "   (missing!)"
        print(f"   {p}{flag}")


# --------------------------------------------------------------------------- steps


def cmd_init(args):
    work = Work(args.workdir)
    if osp.exists(work.config_path) and not args.force:
        sys.exit(f"{work.root} is already initialised (use --force to re-initialise).")
    require(args.materials, "Give the folder with your idea and experimental log.")
    require(osp.join(args.template, "template.tex"), "Template folder needs template.tex")
    require(osp.join(args.template, "guidelines.md"), "Template folder needs guidelines.md")

    cfg = dict(DEFAULT_CONFIG)
    cfg["idea_filename"] = args.idea_filename
    cfg["experimental_log_filename"] = args.log_filename
    cfg["research_cutoff"] = args.cutoff or datetime.datetime.now().strftime("%Y-%m")
    for key in ("writer_model", "reflection_model", "plotting_model", "image_model"):
        if getattr(args, key):
            cfg[key] = getattr(args, key)

    for fname in (cfg["idea_filename"], cfg["experimental_log_filename"]):
        require(osp.join(args.materials, fname), f"Raw materials must contain {fname}")

    os.makedirs(work.root, exist_ok=True)
    if osp.abspath(args.materials) != work.materials:
        shutil.copytree(args.materials, work.materials, dirs_exist_ok=True)
    shutil.copytree(args.template, work.latex, dirs_exist_ok=True)
    shutil.copy(work.template, work.template_skeleton)
    os.makedirs(work.figures, exist_ok=True)
    if not osp.exists(work.figures_info):
        save_figures_info(work, [])
    with open(work.config_path, "w") as f:
        json.dump(cfg, f, indent=2)
    work.mark("init", materials=osp.abspath(args.materials), template=osp.abspath(args.template))

    print(f"Initialised {work.root}")
    print(json.dumps(cfg, indent=2))
    print(
        "\nBefore `outline`, review/edit:\n"
        f"   {work.idea}\n   {work.log}\n"
        f"   {work.template}   (title, authors, keywords, acknowledgments)\n"
        f"   {work.guidelines}"
    )


def cmd_outline(args):
    from google.genai import types  # noqa: F401  (ensures dependency is importable)
    from methods.agents.outline_agent import OutlineAgent

    work = Work(args.workdir)
    cfg = work.load_config()
    model = args.model or cfg["writer_model"]
    backup(work, "outline", [work.outline])

    t0 = time.time()
    OutlineAgent(model_name=model, cutoff_date=cfg["research_cutoff"]).run(
        idea_file=work.idea,
        experimental_log_file=work.log,
        latex_template_file=work.template_skeleton,
        conference_guidelines_file=work.guidelines,
        output_filepath=work.outline,
    )
    work.mark("outline", model=model)
    report(t0, [work.outline])
    print(
        "\nIn outline.json check: plotting_plan (figures to generate), "
        "intro_related_work_plan (search queries), section_plan (structure, citation_hints)."
    )


def cmd_literature(args):
    from methods.agents.literature_review_agent import HybridLiteratureAgent

    work = Work(args.workdir)
    cfg = work.load_config()
    require(work.outline, "Run `outline` first.")
    model = args.model or cfg["writer_model"]
    backup(work, "literature", [work.lit_dir, work.template])

    t0 = time.time()
    agent = HybridLiteratureAgent(
        idea_path=work.idea,
        experimental_log_path=work.log,
        latex_template_path=work.template_skeleton,
        conference_guidelines_path=work.guidelines,
        output_dir=work.lit_dir,
        model_name=model,
        max_workers=cfg["literature_max_workers"],
    )
    agent.run(outline_path=work.outline, cutoff_date=cfg["research_cutoff"])

    # Same hand-off as the original pipeline: the filled-in template and the
    # bibliography become the writer's starting point.
    shutil.copy(osp.join(work.lit_dir, "updated_template.tex"), work.template)
    shutil.copy(osp.join(work.lit_dir, "references.bib"), osp.join(work.latex, "references.bib"))
    work.mark("literature", model=model)

    pdf = compile_tex(work.template)
    report(
        t0,
        [
            osp.join(work.lit_dir, "references.bib"),
            work.citation_map,
            work.template,
            pdf or osp.join(work.latex, "template.pdf"),
        ],
    )
    print(
        "\nReview the cited papers (citation_map.json) and the Introduction/Related Work in "
        "latex_writeup/template.tex. Edits to template.tex are kept by `write`."
    )


def cmd_plotting(args):
    from methods.agents.plotting_agent import PlottingAgent

    work = Work(args.workdir)
    cfg = work.load_config()
    require(work.outline, "Run `outline` first.")
    model = args.model or cfg["plotting_model"]
    backup(work, "plotting", [work.plot_dir])

    t0 = time.time()
    results = PlottingAgent(
        model_name=model,
        image_model_name=args.image_model or cfg["image_model"],
        max_critic_rounds=cfg["plotting_max_critic_rounds"],
    ).run(
        outline_json_path=work.outline,
        raw_materials_dir=work.materials,
        output_filepath=work.plot_results,
    )

    # Register generated figures (replacing earlier generated ones, keeping user figures).
    info = [f for f in load_figures_info(work) if f.get("source") != "plotting_agent"]
    new_files = []
    for res in results or []:
        if "image_path" not in res:
            continue
        src = osp.join(work.plot_dir, res["image_path"])
        if not osp.exists(src):
            continue
        name = osp.basename(src)
        shutil.copy(src, osp.join(work.figures, name))
        info.append({"name": name, "caption": res.get("caption", ""), "source": "plotting_agent"})
        new_files.append(osp.join(work.figures, name))
    save_figures_info(work, info)
    work.mark("plotting", model=model, n_figures=len(new_files))
    report(t0, [work.plot_results, work.figures_info] + new_files)


def cmd_add_figure(args):
    work = Work(args.workdir)
    work.load_config()
    require(args.file, "Figure file not found.")
    ext = osp.splitext(args.file)[1].lower()
    if ext not in FIGURE_EXTS:
        sys.exit(f"Unsupported figure type {ext}; use one of {FIGURE_EXTS}")
    name = args.name or osp.basename(args.file)
    shutil.copy(args.file, osp.join(work.figures, name))
    info = [f for f in load_figures_info(work) if f["name"] != name]
    info.append({"name": name, "caption": args.caption, "source": "user"})
    save_figures_info(work, info)
    print(f"Added figures/{name}. Registered figures:")
    for f in info:
        print(f"   [{f.get('source', '?')}] {f['name']}: {f['caption'][:80]}")


def cmd_remove_figure(args):
    work = Work(args.workdir)
    info = load_figures_info(work)
    kept = [f for f in info if f["name"] != args.name]
    if len(kept) == len(info):
        sys.exit(f"No registered figure named {args.name}")
    save_figures_info(work, kept)
    print(f"Unregistered {args.name} (file left in figures/).")


def cmd_write(args):
    from methods.agents.section_writing_agent import SectionWritingAgent

    work = Work(args.workdir)
    cfg = work.load_config()
    require(work.citation_map, "Run `literature` first.")
    model = args.model or cfg["writer_model"]
    outline = work.lit_outline if osp.exists(work.lit_outline) else work.outline
    backup(work, "write", [work.draft, work.draft.replace(".tex", ".pdf")])

    t0 = time.time()
    SectionWritingAgent(
        outline_path=outline,
        template_path=work.template,
        idea_path=work.idea,
        experimental_log_path=work.log,
        citation_map_path=work.citation_map,
        figures_info_path=work.figures_info,
        guidelines_path=work.guidelines,
        model_name=model,
    ).run(output_path=work.draft)
    pdf = compile_tex(work.draft) if osp.exists(work.draft) else None
    work.mark("write", model=model, compiled=bool(pdf))
    report(t0, [work.draft, pdf or work.draft.replace(".tex", ".pdf")])
    if not pdf:
        print("   PDF did not compile; see latex_writeup/raw_draft_paper.log")


def cmd_refine(args):
    from methods.agents.content_refinement_agent import ContentRefinementAgent

    work = Work(args.workdir)
    cfg = work.load_config()
    require(work.draft, "Run `write` first.")
    model = args.model or cfg["reflection_model"]

    rounds = work.refine_rounds()
    if args.from_tex:
        src_tex = osp.abspath(args.from_tex)
    elif rounds:
        src_tex = osp.join(work.refine_dir, rounds[-1], "final_refined_paper.tex")
    else:
        src_tex = work.draft
    require(src_tex, "Input .tex for refinement not found.")

    n = int(rounds[-1].split("_")[1]) + 1 if rounds else 1
    round_dir = osp.join(work.refine_dir, f"round_{n}")
    # Start from the LaTeX folder (class files, figures, bib) plus the input .tex.
    shutil.copytree(work.latex, round_dir)
    input_tex = osp.join(round_dir, "input_paper.tex")
    shutil.copy(src_tex, input_tex)
    print(f" >> Refinement round {n}: input {src_tex}")

    t0 = time.time()
    agent = ContentRefinementAgent(
        experimental_log_path=work.log,
        citation_map_path=work.citation_map,
        guidelines_path=work.guidelines,
        model_name=model,
        max_reflections=args.rounds,
        work_dir=round_dir,
    )
    out_pdf = agent.run(texfile_path=input_tex)
    work.mark(f"refine_round_{n}", model=model, input=src_tex, reflections=args.rounds)
    report(
        t0,
        [
            osp.join(round_dir, "content_refinement_worklog.json"),
            osp.join(round_dir, "final_refined_paper.tex"),
            out_pdf if isinstance(out_pdf, str) and out_pdf.endswith(".pdf") else
            osp.join(round_dir, "final_refined_paper.pdf"),
        ],
    )
    print(
        "\nThe worklog has reviewer scores and what changed. To refine a hand-edited "
        "version next, pass --from-tex <file>."
    )


def cmd_status(args):
    work = Work(args.workdir)
    cfg = work.load_config()
    state = work.load_state()
    print(f"Work directory: {work.root}")
    print(
        f"Models: writer={cfg['writer_model']} reflection={cfg['reflection_model']} "
        f"plotting={cfg['plotting_model']} image={cfg['image_model']}"
    )
    print(f"Research cutoff: {cfg['research_cutoff']}\n")
    for step in ("init", "outline", "literature", "plotting", "write"):
        s = state.get(step)
        print(f"  {'[x]' if s else '[ ]'} {step:11s} {s['finished'] if s else ''}")
    for r in work.refine_rounds():
        s = state.get(f"refine_{r}", {})
        print(f"  [x] refine {r:6s} {s.get('finished', '')}")
    figs = load_figures_info(work)
    print(f"\nRegistered figures ({len(figs)}):")
    for f in figs:
        print(f"   [{f.get('source', '?')}] {f['name']}")


# --------------------------------------------------------------------------- CLI


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="step", required=True)

    def add(name, func, help_, model=True):
        sp = sub.add_parser(name, help=help_)
        sp.add_argument("--workdir", required=True)
        if model:
            sp.add_argument("--model", help="Override the model from config.json for this run.")
        sp.set_defaults(func=func)
        return sp

    sp = add("init", cmd_init, "Create a work directory.", model=False)
    sp.add_argument("--materials", required=True, help="Folder with idea and experimental log.")
    sp.add_argument("--template", default=osp.join(REPO_DIR, "templates", "aastex7"))
    sp.add_argument("--idea-filename", default=DEFAULT_CONFIG["idea_filename"])
    sp.add_argument("--log-filename", default=DEFAULT_CONFIG["experimental_log_filename"])
    sp.add_argument("--cutoff", help="Research cutoff YYYY-MM (default: this month).")
    sp.add_argument("--writer-model", dest="writer_model")
    sp.add_argument("--reflection-model", dest="reflection_model")
    sp.add_argument("--plotting-model", dest="plotting_model")
    sp.add_argument("--image-model", dest="image_model")
    sp.add_argument("--force", action="store_true")

    add("outline", cmd_outline, "Generate outline.json.")
    add("literature", cmd_literature, "Search literature; write Introduction + Related Work.")
    sp = add("plotting", cmd_plotting, "Generate figures from the outline's plotting_plan.")
    sp.add_argument("--image-model", dest="image_model")

    sp = add("add-figure", cmd_add_figure, "Register your own figure.", model=False)
    sp.add_argument("--file", required=True)
    sp.add_argument("--caption", required=True)
    sp.add_argument("--name", help="File name inside figures/ (default: original name).")

    sp = add("remove-figure", cmd_remove_figure, "Unregister a figure.", model=False)
    sp.add_argument("--name", required=True)

    add("write", cmd_write, "Write the remaining sections -> raw_draft_paper.tex.")
    sp = add("refine", cmd_refine, "Review and revise the draft (one new round folder per run).")
    sp.add_argument("--rounds", type=int, default=1, help="Review/revise iterations in this run.")
    sp.add_argument("--from-tex", help="Refine this .tex instead of the latest result.")

    add("status", cmd_status, "Show progress.", model=False)

    args = p.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
